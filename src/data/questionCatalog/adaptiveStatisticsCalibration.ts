export const adaptiveStatisticsCalibrationQuestions: Question[] = allDefinitions.map((definition) => {
  const question = makeSimpleQuestion(
    definition.id,
    'Statistics',
    CHAPTER,
    definition.title,
    definition.prompt,
    definition.correct,
    definition.wrong,
    definition.lesson,
    SOURCE,
    false,
    definition.mentorHint,
    {
      challengeRating: definition.challengeRating,
      solution: definition.solution,
      alternatePrompts: {
        plain: definition.plain,
        teaching: definition.teaching,
      },
    },
  )
  const mindset = calibrationMindsets[definition.mindsetId ?? definition.id]

  return {
    ...question,
    answers: question.answers.map((answer) => {
      if (answer.correct || !mindset || !answer.misconceptions?.length) return answer
      return {
        ...answer,
        misconceptions: answer.misconceptions.map((misconception) => ({
          ...misconception,
          tempting: `This is the ${mindset.trap}. ${mindset.aha}`,
        })),
      }
    }),
    difficulty: definition.difficulty,
    xp: 10 + definition.difficulty,
  }
})
